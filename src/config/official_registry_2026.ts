export interface OfficerJurisdictionLookup {
  isVerified: boolean;
  source: 'NATIONAL_HELPLINE' | 'STATE_HELPLINE' | 'DISTRICT_REGISTRY' | 'SEEDED_CATALOG';
  number: string;
  category: 'ROADS' | 'WATER' | 'SANITATION' | 'ELECTRICITY' | 'COLLECTORATE' | 'PUBLIC_SAFETY';
  department: string;
  scope: 'NATIONAL' | 'STATE' | 'DISTRICT';
  stateName?: string;
  districtName?: string;
  districtId?: number;
  rbacRole: 'System Admin' | 'State Moderator' | 'Department Operator';
}

/**
 * Normalizes any phone number or shortcode to clean digits.
 */
export function normalizePhoneNumber(raw: string): string {
  return String(raw || '').replace(/\D/g, '');
}

/**
 * Validates whether an incoming phone matches a verified government helpline/officer number.
 * Returns the matched department, category, jurisdiction scope, and RBAC role.
 */
export function lookupOfficerJurisdictionByPhone(rawPhone: string): OfficerJurisdictionLookup | null {
  const clean = normalizePhoneNumber(rawPhone);
  if (!clean) return null;

  // 1. Check Universal National Helplines
  for (const nh of OFFICIAL_REGISTRY_2026.universal_national_helplines) {
    const cleanNH = normalizePhoneNumber(nh.number);
    if (clean === cleanNH || clean.endsWith(cleanNH)) {
      return {
        isVerified: true,
        source: 'NATIONAL_HELPLINE',
        number: nh.number,
        category: nh.category,
        department: nh.department,
        scope: nh.scope,
        rbacRole: nh.scope === 'NATIONAL' ? 'System Admin' : 'State Moderator',
      };
    }
  }

  // 2. Check States & Districts Registry
  for (const st of OFFICIAL_REGISTRY_2026.state_and_district_registry) {
    // Check State Helplines
    const categories: Array<'COLLECTORATE' | 'ROADS' | 'WATER' | 'SANITATION' | 'ELECTRICITY'> = [
      'COLLECTORATE',
      'ROADS',
      'WATER',
      'SANITATION',
      'ELECTRICITY',
    ];

    for (const cat of categories) {
      const nums = st.state_helplines[cat] || [];
      for (const num of nums) {
        const cleanNum = normalizePhoneNumber(num);
        if (clean === cleanNum || (clean.length === 10 && cleanNum.endsWith(clean)) || (cleanNum.length === 10 && clean.endsWith(cleanNum))) {
          const dept = OFFICIAL_REGISTRY_2026.category_taxonomy[cat as keyof typeof OFFICIAL_REGISTRY_2026.category_taxonomy]?.department_name || `${st.state} State ${cat} Command`;
          return {
            isVerified: true,
            source: 'STATE_HELPLINE',
            number: num,
            category: cat,
            department: dept,
            scope: 'STATE',
            stateName: st.state,
            rbacRole: 'State Moderator',
          };
        }
      }
    }

    // Check District Helplines
    for (const dist of st.districts) {
      for (const cat of categories) {
        const nums = dist[cat] || [];
        for (const num of nums) {
          const cleanNum = normalizePhoneNumber(num);
          if (clean === cleanNum || (clean.length === 10 && cleanNum.endsWith(clean)) || (cleanNum.length === 10 && clean.endsWith(cleanNum))) {
            const dept = OFFICIAL_REGISTRY_2026.category_taxonomy[cat as keyof typeof OFFICIAL_REGISTRY_2026.category_taxonomy]?.department_name || `${dist.district} ${cat} Municipal Operations`;
            return {
              isVerified: true,
              source: 'DISTRICT_REGISTRY',
              number: num,
              category: cat,
              department: dept,
              scope: 'DISTRICT',
              stateName: st.state,
              districtName: dist.district,
              rbacRole: 'Department Operator',
            };
          }
        }
      }
    }
  }

  return null;
}

/**
 * Returns all assigned official helpline numbers for a given state, district, and category.
 */
export function getHelplinesForDistrict(
  stateName: string,
  districtName: string,
  category: 'ROADS' | 'WATER' | 'SANITATION' | 'ELECTRICITY' | 'COLLECTORATE'
): { primary: string[]; fallback: string[]; department: string; escalationHours: number } {
  const normState = (stateName || '').toLowerCase().trim();
  const normDist = (districtName || '').toLowerCase().trim();

  const stateObj = OFFICIAL_REGISTRY_2026.state_and_district_registry.find(
    (s) => s.state.toLowerCase().trim() === normState
  );

  const taxonomy = OFFICIAL_REGISTRY_2026.category_taxonomy[category as keyof typeof OFFICIAL_REGISTRY_2026.category_taxonomy];
  const department = taxonomy?.department_name || `${category} Operations`;
  const escalationHours = taxonomy?.escalation_threshold_hours || 48;
  const fallbackShortcode = taxonomy?.fallback_shortcode || '112';

  if (!stateObj) {
    return {
      primary: [],
      fallback: [fallbackShortcode],
      department,
      escalationHours,
    };
  }

  const distObj = stateObj.districts.find(
    (d) => d.district.toLowerCase().trim() === normDist || normDist.includes(d.district.toLowerCase().trim())
  );

  const districtNumbers = distObj ? distObj[category] || [] : [];
  const stateNumbers = stateObj.state_helplines[category] || [];

  return {
    primary: districtNumbers.length > 0 ? districtNumbers : stateNumbers,
    fallback: [fallbackShortcode, ...(stateObj.state_helplines.COLLECTORATE || [])],
    department,
    escalationHours,
  };
}

/**
 * Classifies complaint description text using official 2026 Category Taxonomy keywords.
 */
export function classifyComplaintCategory(descriptionText: string): {
  category: 'ROADS' | 'WATER' | 'SANITATION' | 'ELECTRICITY';
  department_name: string;
  default_priority: 'LOW' | 'MEDIUM' | 'HIGH' | 'CRITICAL';
  escalation_threshold_hours: number;
  matched_keywords: string[];
} {
  const text = (descriptionText || '').toLowerCase();
  const scores: Record<'ROADS' | 'WATER' | 'SANITATION' | 'ELECTRICITY', { score: number; matched: string[] }> = {
    ROADS: { score: 0, matched: [] },
    WATER: { score: 0, matched: [] },
    SANITATION: { score: 0, matched: [] },
    ELECTRICITY: { score: 0, matched: [] },
  };

  for (const [catKey, rule] of Object.entries(OFFICIAL_REGISTRY_2026.category_taxonomy)) {
    const k = catKey as 'ROADS' | 'WATER' | 'SANITATION' | 'ELECTRICITY';
    for (const kw of rule.keywords) {
      if (text.includes(kw.toLowerCase())) {
        scores[k].score += 1;
        scores[k].matched.push(kw);
      }
    }
  }

  // Find category with highest match score
  let bestCategory: 'ROADS' | 'WATER' | 'SANITATION' | 'ELECTRICITY' = 'ROADS';
  let highestScore = -1;

  for (const [catKey, data] of Object.entries(scores)) {
    const k = catKey as 'ROADS' | 'WATER' | 'SANITATION' | 'ELECTRICITY';
    if (data.score > highestScore) {
      highestScore = data.score;
      bestCategory = k;
    }
  }

  const rule = OFFICIAL_REGISTRY_2026.category_taxonomy[bestCategory];
  return {
    category: bestCategory,
    department_name: rule.department_name,
    default_priority: rule.default_priority,
    escalation_threshold_hours: rule.escalation_threshold_hours,
    matched_keywords: scores[bestCategory].matched,
  };
}

/**
 * Returns a flat set of all whitelisted official phone numbers across the nation.
 */
export function getAllWhitelistedOfficerPhones(): Set<string> {
  const set = new Set<string>();

  for (const nh of OFFICIAL_REGISTRY_2026.universal_national_helplines) {
    set.add(normalizePhoneNumber(nh.number));
  }

  for (const st of OFFICIAL_REGISTRY_2026.state_and_district_registry) {
    for (const list of Object.values(st.state_helplines)) {
      for (const num of list) {
        set.add(normalizePhoneNumber(num));
      }
    }
    for (const dist of st.districts) {
      for (const list of [dist.COLLECTORATE, dist.ROADS, dist.WATER, dist.SANITATION, dist.ELECTRICITY]) {
        for (const num of list) {
          set.add(normalizePhoneNumber(num));
        }
      }
    }
  }

  return set;
}

